                    FeatureHighlightRow(
                        icon = Icons.Default.Speed,
                        title = "Historique Diagnostics",
                        subtitle = "Conservez les résultats des tests de débit et de latence"
                    )
                    FeatureHighlightRow(
                        icon = Icons.Default.Security,
                        title = "Sécurité Zero-Trust",
