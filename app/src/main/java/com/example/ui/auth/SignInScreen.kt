            )
            Text(
                text = subtitle,
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant
            )
        }
    }
}

fun launchGoogleSignIn(
    context: Context,
    scope: CoroutineScope,
    authViewModel: AuthViewModel
) {
    val credentialManager = CredentialManager.create(context)
    val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
    val webClientId = if (resId != 0) context.getString(resId) else ""

    if (webClientId.isBlank()) {
        Log.e("SignInScreen", "default_web_client_id string resource not found")
        return
    }

    val googleIdOption = GetSignInWithGoogleOption.Builder(webClientId)
        .build()

    val request = GetCredentialRequest.Builder()
        .addCredentialOption(googleIdOption)
        .build()

    scope.launch {
        try {
            val result = credentialManager.getCredential(
                request = request,
                context = context
            )
            val credential = result.credential
            if (credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
                authViewModel.signInWithGoogleIdToken(googleIdTokenCredential.idToken)
            }
        } catch (e: GetCredentialCancellationException) {
            Log.w("SignInScreen", "Google Sign-In was cancelled by user")
            authViewModel.resetError()
        } catch (e: GetCredentialException) {
            Log.e("SignInScreen", "Google Sign-In failed", e)
        }
    }
}
